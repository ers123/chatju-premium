/**
 * SoMyung Content Repurpose — Korean & Japanese content banks.
 *
 * Why authored, not translated:
 *   The English engine's two content sources were measured against each other.
 *   Hand-written bank snippets came out publishable; machine-sliced blog text
 *   came out as markdown fragments. Translating the sliced English would have
 *   carried that defect into two more languages and added a translation-quality
 *   problem on top. So ko/ja are written natively here.
 *
 * Why only ko/ja/en:
 *   Real usage is ko 12 / ja 6 / en 6. The other seven locales have zero users —
 *   marketing copy for them would be inventory, not reach.
 *
 * Voice rules (same intent as the English bank, different execution):
 *   - Never "점" / "占い" (fortune-telling). Use 기질 분석 / 気質分析.
 *   - Parent-to-parent, not brand-to-consumer. No exclamation stacking.
 *   - ko: 해요체. Warm, specific, slightly wry. Korean parents know 사주 already —
 *     the job is to move it from 미신 to 기질, not to explain what it is.
 *   - ja: です・ます. Softer assertions, more hedging than Korean — a flat
 *     imperative reads as rude. 四柱推命 is recognized, so lead with the child,
 *     not the system.
 */

