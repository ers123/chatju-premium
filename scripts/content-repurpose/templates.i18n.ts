/**
 * X/Twitter counts CJK as 2 units against the 280 limit, so Korean and
 * Japanese posts effectively get ~140 characters. Counting `.length` here
 * would let a 200-character Korean post look "safe" and then be rejected.
 */
export function weightedLength(text: string): number {
  let n = 0;
  for (const ch of text) {
    n += /[ᄀ-ᇿ⺀-鿿ꥠ-꥿가-퟿豈-﫿＀-｠]/.test(ch) ? 2 : 1;
  }
  return n;
}
